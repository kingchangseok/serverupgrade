/*****************************************************************/
int main(int argc, char **argv, char **envp)
{
char	md5sumval                  [256];


	if (md5sum(argv[1], md5sumval) != 0)
		exit (1);

	fprintf(stdout, "%s\n", md5sumval);

	exit (0);

}

