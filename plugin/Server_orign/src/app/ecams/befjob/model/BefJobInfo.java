package app.ecams.befjob.model;

public class BefJobInfo{
	private String crAcptno;
	private String crAcptdate;
	private String crSysmsg;
	private String crUsername;
	private String crStatus;
	private String crSayu;
	
	public String getCrAcptdate() {
		return crAcptdate;
	}
	public void setCrAcptdate(String crAcptdate) {
		this.crAcptdate = crAcptdate;
	}
	public String getCrSysmsg() {
		return crSysmsg;
	}
	public void setCrSysmsg(String crSysmsg) {
		this.crSysmsg = crSysmsg;
	}
	public String getCrUsername() {
		return crUsername;
	}
	public void setCrUsername(String crUsername) {
		this.crUsername = crUsername;
	}
	public String getCrStatus() {
		return crStatus;
	}
	public void setCrStatus(String crStatus) {
		this.crStatus = crStatus;
	}
	public String getCrSayu() {
		return crSayu;
	}
	public void setCrSayu(String crSayu) {
		this.crSayu = crSayu;
	}
	public void setCrAcptno(String crAcptno) {
		this.crAcptno = crAcptno;
	}
	public String getCrAcptno() {
		return crAcptno;
	}
}